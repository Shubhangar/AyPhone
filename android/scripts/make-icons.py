#!/usr/bin/env python3
"""Generates the Android icons from assets/logo.svg as vector drawables.

Writes, under app/src/main/res/:
  drawable/ic_launcher_background.xml   the logo's background gradient (adaptive icon)
  drawable/ic_launcher_foreground.xml   the artwork, scaled into the adaptive-icon safe zone
  drawable/ic_launcher_monochrome.xml   white silhouette for Android's themed icons
  drawable/ic_stat_ayphone.xml          white silhouette for the status bar
  drawable/ic_logo.xml                  the logo alone (white, no background) for use inside the app
  mipmap-anydpi-v26/ic_launcher.xml     the adaptive icon tying them together

Handles what the logo uses: one rounded-rect background with a linear gradient, and paths
filled with either a linear gradient or a solid colour.
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "..", "assets", "logo.svg")
RES = os.path.join(ROOT, "app", "src", "main", "res")
NS = {"s": "http://www.w3.org/2000/svg"}

# The 300-unit artwork is centred around (161, 150); adaptive icons only guarantee the
# central 66 of 108 dp, so the foreground is scaled into that zone.
SAFE = ('android:pivotX="161" android:pivotY="150" android:scaleX="0.74" android:scaleY="0.74" '
        'android:translateX="-11" android:translateY="0"')
STATUS = ('android:pivotX="161" android:pivotY="150" android:scaleX="1.42" android:scaleY="1.42" '
          'android:translateX="-11" android:translateY="0"')
LOGO = ('android:pivotX="161" android:pivotY="150" android:scaleX="1.2" android:scaleY="1.2" '
        'android:translateX="-11" android:translateY="0"')
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/make-icons.py from assets/logo.svg -->\n'
VECTOR = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="{size}dp" android:height="{size}dp"\n'
          '    android:viewportWidth="300" android:viewportHeight="300">\n')


def argb(color):
    color = color.strip().lstrip("#")
    if color.lower() == "white":
        color = "FFFFFF"
    return "#FF" + color.upper()


def load():
    tree = ET.parse(SVG)
    root = tree.getroot()
    gradients = {}
    for g in root.iter("{http://www.w3.org/2000/svg}linearGradient"):
        stops = [(float(s.get("offset", "0")), argb(s.get("stop-color", "#000000")))
                 for s in g.findall("s:stop", NS)]
        gradients[g.get("id")] = {k: g.get(k) for k in ("x1", "y1", "x2", "y2")} | {"stops": stops}
    rect = root.find("s:rect", NS)
    paths = [(p.get("d"), p.get("fill")) for p in root.findall("s:path", NS)]
    return rect.get("fill"), paths, gradients


def gradient_xml(ref, gradients, indent):
    g = gradients[re.match(r"url\(#(.+)\)", ref).group(1)]
    items = "\n".join(f'{indent}        <item android:offset="{o:g}" android:color="{c}" />' for o, c in g["stops"])
    return (f'{indent}<aapt:attr name="android:fillColor">\n'
            f'{indent}    <gradient android:type="linear" android:startX="{g["x1"]}" android:startY="{g["y1"]}" '
            f'android:endX="{g["x2"]}" android:endY="{g["y2"]}">\n{items}\n'
            f'{indent}    </gradient>\n{indent}</aapt:attr>')


def path_xml(d, fill, gradients, indent, mono=None):
    if mono:
        return f'{indent}<path android:fillColor="{mono}" android:pathData="{d}" />'
    if fill and fill.startswith("url("):
        return f'{indent}<path android:pathData="{d}">\n{gradient_xml(fill, gradients, indent + "    ")}\n{indent}</path>'
    return f'{indent}<path android:fillColor="{argb(fill or "#000000")}" android:pathData="{d}" />'


def write(rel, text):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    bg, paths, gradients = load()
    glyphs = lambda indent, mono=None: "\n".join(path_xml(d, f, gradients, indent, mono) for d, f in paths)
    full_rect = "M0,0h300v300h-300z"
    rounded = "M30,0h240a30,30 0,0 1,30 30v240a30,30 0,0 1,-30 30h-240a30,30 0,0 1,-30 -30v-240a30,30 0,0 1,30 -30z"

    write("drawable/ic_launcher_background.xml", HEAD + VECTOR.format(size=108) +
          f'    <path android:pathData="{full_rect}">\n{gradient_xml(bg, gradients, "        ")}\n    </path>\n</vector>\n')
    write("drawable/ic_launcher_foreground.xml", HEAD + VECTOR.format(size=108) +
          f"    <group {SAFE}>\n{glyphs('        ')}\n    </group>\n</vector>\n")
    write("drawable/ic_launcher_monochrome.xml", HEAD + VECTOR.format(size=108) +
          f"    <group {SAFE}>\n{glyphs('        ', '#FFFFFFFF')}\n    </group>\n</vector>\n")
    write("drawable/ic_stat_ayphone.xml", HEAD + VECTOR.format(size=24) +
          f"    <group {STATUS}>\n{glyphs('        ', '#FFFFFFFF')}\n    </group>\n</vector>\n")
    write("drawable/ic_logo.xml", HEAD + VECTOR.format(size=64) +
          f"    <group {LOGO}>\n{glyphs('        ', '#FFFFFFFF')}\n    </group>\n</vector>\n")
    write("mipmap-anydpi-v26/ic_launcher.xml", '<?xml version="1.0" encoding="utf-8"?>\n'
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@drawable/ic_launcher_background" />\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
          '</adaptive-icon>\n')
    print(f"Wrote Android icons from {len(paths)} paths")


if __name__ == "__main__":
    main()
